"""NEC-04F: original six-world matched-auxiliary Looper primary/retention gate.

Require ALL six independent root audits × three fixed native training arms ×
two continuous AdamW checkpoints. Original calibration WORLD is statistical
unit; all 32-mask contexts within a root are correlated. No fresh model,
SAE, sham or held-out WORLD outcomes are generated by this aggregate.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
import json
from math import sqrt
from pathlib import Path

ROOTS=tuple(range(12,18))
ARMS=("aux_shuffled","aux_prefix","vanilla")
STEPS=(240,900)
SOURCE=2560
VALIDATION=768
STAGES=(2,3,4,5)
SCHEMA="NEC-04F/frozen-six-root-auxiliary-XOR-primary-gate-aggregate/v1"
DELTA_MIN=.10
POSITIVE_MIN=4
PREFIX_ACC_MIN=.60
ALTERNATE_FLOOR=-.05


def file_sha(path):
    return sha256(Path(path).read_bytes()).hexdigest()


def require(ok,why):
    if not ok:
        raise AssertionError(why)


def per_root_walsh(validation_rows,all_native_logits):
    """First-class final-logit fifth-order Fourier output power diagnostic."""
    require(len(validation_rows)==VALIDATION and len(all_native_logits)==SOURCE+VALIDATION,
            "read-only complete owned validation mask panels required")
    fractions=[]
    parity_count=0
    for group in range(24):
        block=validation_rows[group*32:(group+1)*32]
        if block[0]["mux_selector"]!=1:
            continue
        assert all(row["mux_selector"]==1 and row["focal_mask"]==mask
                   for mask,row in enumerate(block))
        margins=[all_native_logits[SOURCE+32*group+mask][1]-
                 all_native_logits[SOURCE+32*group+mask][0] for mask in range(32)]
        coefficients=[
            sum(v*(-1 if (mask & subset).bit_count()%2 else 1)
                for mask,v in enumerate(margins))/32
            for subset in range(32)
        ]
        energy=sum(v*v for v in coefficients[1:])
        fractions.append(coefficients[31]**2/energy if energy>1e-20 else None)
        parity_count+=32
    require(bool(fractions),"no original parity-selector contexts to score")
    positive=[value for value in fractions if value is not None]
    return {
        "original_parity_cases":parity_count,
        "parity_context_groups":len(fractions),
        "zero_focal_logit_variance_groups":len(fractions)-len(positive),
        "mean_true_five_bit_walsh_power_share":(
            sum(positive)/len(positive) if positive else None
        ),
    }


def root_summary(values):
    if not values:
        raise AssertionError("missing independent original calibration root observations")
    mean=sum(values)/len(values)
    variance=sum((x-mean)**2 for x in values)/(len(values)-1)
    return {
        "mean":mean,
        "root_sd_descriptive":sqrt(variance),
        "root_standard_error_descriptive":sqrt(variance/len(values)),
        "values_in_original_root_order":values,
        "n_independent_calibration_worlds":len(values),
    }


def aggregate(roots_folder:Path,pretraining:Path,out:Path):
    ledger_file=pretraining/"nec04f_pretraining_oracles.json"
    ledger=json.loads(ledger_file.read_text())
    require(
        ledger["schema"]=="NEC-04F/original-six-calibration-root-auxiliary-teacher-ledger/v1"
        and ledger["root_indices"]==list(ROOTS)
        and ledger["training_arms"]==list(ARMS)
        and ledger["stage_k"]==list(STAGES)
        and ledger["checkpoint_steps"]==list(STEPS)
        and ledger["original_source_rows_per_root"]==SOURCE
        and ledger["original_owned_validation_rows_per_root"]==VALIDATION
        and ledger["optimizer_updates_before_preflight"]==0
        and len(ledger["roots"])==len(ROOTS)
        and ledger["FSI_01_gate"]=="REDESIGN_OR_PILOT_ONLY",
        "precommitted six-world root/auxiliary preregistration missing")
    require(
        {p.name for p in roots_folder.iterdir() if p.is_dir()}==
        {f"nec04f-native-root-{index}" for index in ROOTS},
        "six entire independent native root audit artifacts required",
    )
    all_root=[]
    for ordinal,index in enumerate(ROOTS):
        root_ref=ledger["roots"][ordinal]
        folder=roots_folder/f"nec04f-native-root-{index}"
        original_file=folder/"nec04f_native_root_result.json"
        audit_file=folder/"nec04f_independent_native_audit.json"
        original=json.loads(original_file.read_text())
        audit=json.loads(audit_file.read_text())
        pretraining_root=pretraining/root_ref["rows_file"]
        require(file_sha(pretraining_root)==root_ref["rows_sha256"],
                "original frozen source and owned validation labels changed")
        require(
            original["schema"]==
            "NEC-04F/three-arm-recurrent-auxiliary-XOR-native-900steps/v1"
            and audit["schema"]==
            "NEC-04F/independent-three-arm-native-optimizer-aux-logit-replay/v1"
            and original["root_index"]==audit["root_index"]==root_ref["index"]==index
            and original["world_id"]==audit["world_id"]==root_ref["world_id"]
            and original["world_sha256"]==audit["world_sha256"]==root_ref["world_sha256"]
            and original["original_program_sha256"]==root_ref["program_sha256"]
            and original["original_source_validation_sha256"]==
            audit["original_source_and_validation_sha256"]==root_ref["rows_sha256"]
            and original["pretraining_oracle_ledger_sha256"]==
            audit["original_pretraining_ledger_sha256"]==file_sha(ledger_file)
            and audit["original_root_scored_receipt_sha256"]==file_sha(original_file)
            and original["source_cases"]==SOURCE
            and original["owned_calibration_validation_cases"]==VALIDATION
            and original["optimizer_updates_per_arm"]==900
            and original["native_initial_weights_shared_all_arms"] is True
            and original["source_batch_order_matched_all_arms"] is True
            and original["model_checkpoints_sealed_before_validation"] is True
            and audit["all_six_native_model_optimizer_checkpoints_byte_sha256_verified"] is True
            and audit["all_six_native_full_and_four_auxiliary_logits_independently_replayed"] is True
            and audit["all_six_continuous_optimizer_state_counters_verified"] is True
            and audit["all_three_arm_native_initial_weights_identical"] is True
            and audit["all_three_arm_source_batch_order_sha_equal"] is True
            and audit["optimizer_trajectories_independently_retrained"] is False
            and audit["native_checkpoints_replayed"]==6
            and original["new_source_SAE_training_updates"]==audit["native_SAE_updates"]==0
            and original["original_calibration_reserved_contexts_scored"]==
            audit["original_reserved_contexts_scored"]==0
            and original["development_world_roots_materialized"]==
            audit["new_development_world_roots_generated"]==0
            and original["confirmation_world_roots_materialized"]==
            audit["new_confirmation_world_roots_generated"]==0
            and original["old_nec03p_roots_scored"]==
            audit["old_nec03p_causal_sham_worlds_scored"]==0
            and original["FSI_01_gate"]==audit["FSI_01_gate"]==
            "REDESIGN_OR_PILOT_ONLY"
            and set(original["arms"])==set(ARMS)==set(audit["arms"]),
            "one original world arm/optimizer/scoring audit missing or modified",
        )
        rows=[json.loads(x) for x in pretraining_root.read_text().splitlines()]
        assert len(rows)==SOURCE+VALIDATION
        by_arm={}
        for arm in ARMS:
            evidence=original["arms"][arm]
            independently=audit["arms"][arm]
            manifest=evidence["checkpoint_seal_manifest"]
            require(
                len(evidence["observations"])==len(independently)==len(STEPS)
                and len(manifest["checkpoints"])==len(STEPS)
                and manifest["optimizer_resets"]==0
                and manifest["optimizer_updates_total"]==900
                and manifest["all_native_model_and_optimizer_checkpoints_sealed_before_validation"],
                "native optimizer continuity or checkpoint seal incomplete",
            )
            summaries=[]
            for n,step in enumerate(STEPS):
                orig=evidence["observations"][n]
                tested=independently[n]
                require(
                    orig["step"]==tested["step"]==step
                    and orig["original_checkpoint_sha256"]==
                    tested["original_checkpoint_sha256"]
                    and orig["original_model_sha256"]==tested["model_weight_sha256"]
                    and tested["all_source_owned_native_12step_and_aux_logits_replayed"] is True,
                    "historical independent checkpoint logits do not match scored result",
                )
                val=tested["independent_metrics"]["owned_calibration_validation"]
                src=tested["independent_metrics"]["source_train"]
                by_branch=val["native_by_original_MUX_branch"]
                parity=by_branch["parity"]
                alt=by_branch["alternate"]
                require(
                    parity["cases"]+alt["cases"]==VALIDATION
                    and parity["correct"]+alt["correct"]==
                    val["original_composed_native"]["correct"]
                    and parity["target_positive_count"]*2==parity["cases"],
                    "original five-focal parity branch label balance/denominator altered",
                )
                power=per_root_walsh(rows[SOURCE:],orig["all_final_native_logits"])
                require(power["original_parity_cases"]==parity["cases"],
                        "original native fifth-order Fourier parity panel differs")
                summaries.append({
                    "step":step,
                    "checkpoint_sha256":orig["original_checkpoint_sha256"],
                    "model_sha256":orig["original_model_sha256"],
                    "original_parity_validation_accuracy":parity["accuracy"],
                    "original_alternate_validation_accuracy":alt["accuracy"],
                    "original_complete_validation_accuracy":
                        val["original_composed_native"]["accuracy"],
                    "original_source_accuracy":
                        src["original_composed_native"]["accuracy"],
                    "stage_aux_true_prefix_validation_accuracy":{
                        str(k):val["auxiliary_true_intermediate_XOR"][str(k)]["accuracy"]
                        for k in STAGES
                    },
                    "stage_aux_true_prefix_source_accuracy":{
                        str(k):src["auxiliary_true_intermediate_XOR"][str(k)]["accuracy"]
                        for k in STAGES
                    },
                    "original_five_bit_final_logit_spectrum":power,
                })
            by_arm[arm]=summaries
        all_root.append({
            "root_index":index,"world_id":root_ref["world_id"],
            "tier":root_ref["difficulty_tier"],
            "source_world_sha256":root_ref["world_sha256"],
            "source_program_sha256":root_ref["program_sha256"],
            "root_scored_result_sha256":file_sha(original_file),
            "independent_root_audit_sha256":file_sha(audit_file),
            "stage_visits":root_ref["stage_visits"],
            "by_arm":by_arm,
        })
    snapshots=[]
    for n,step in enumerate(STEPS):
        rows=[]
        for root in all_root:
            shuffle=root["by_arm"]["aux_shuffled"][n]
            prefix=root["by_arm"]["aux_prefix"][n]
            vanilla=root["by_arm"]["vanilla"][n]
            rows.append({
                "root_index":root["root_index"],
                "tier":root["tier"],
                "aux_shuffled_parity_accuracy":shuffle["original_parity_validation_accuracy"],
                "aux_prefix_parity_accuracy":prefix["original_parity_validation_accuracy"],
                "vanilla_parity_accuracy":vanilla["original_parity_validation_accuracy"],
                "primary_parity_delta":(
                    prefix["original_parity_validation_accuracy"]
                    -shuffle["original_parity_validation_accuracy"]
                ),
                "alternate_retention_delta":(
                    prefix["original_alternate_validation_accuracy"]
                    -shuffle["original_alternate_validation_accuracy"]
                ),
                "whole_task_delta":(
                    prefix["original_complete_validation_accuracy"]
                    -shuffle["original_complete_validation_accuracy"]
                ),
                "prefix_true_aux_4bit_validation_accuracy":
                    prefix["stage_aux_true_prefix_validation_accuracy"]["4"],
                "prefix_true_aux_5bit_validation_accuracy":
                    prefix["stage_aux_true_prefix_validation_accuracy"]["5"],
                "shuffled_true_aux_4bit_validation_accuracy":
                    shuffle["stage_aux_true_prefix_validation_accuracy"]["4"],
                "prefix_native_fifth_order_walsh_power_share":
                    prefix["original_five_bit_final_logit_spectrum"]
                    ["mean_true_five_bit_walsh_power_share"],
            })
        parity_delta=[r["primary_parity_delta"] for r in rows]
        retention=[r["alternate_retention_delta"] for r in rows]
        min_native=[r["aux_prefix_parity_accuracy"] for r in rows]
        positive=sum(x>0 for x in parity_delta)
        delta=sum(parity_delta)/len(parity_delta)
        alternate=sum(retention)/len(retention)
        parity_mean=sum(min_native)/len(min_native)
        gate=(step==900
              and delta>=DELTA_MIN
              and positive>=POSITIVE_MIN
              and alternate>=ALTERNATE_FLOOR
              and parity_mean>=PREFIX_ACC_MIN)
        snapshots.append({
            "step":step,
            "predeclared_primary_correctness_endpoint":"original composed full task on MUX=1 parity branch",
            "primary_paired_world_delta":root_summary(parity_delta),
            "aux_prefix_parity_native_accuracy":root_summary(min_native),
            "aux_shuffled_parity_native_accuracy":
                root_summary([r["aux_shuffled_parity_accuracy"] for r in rows]),
            "vanilla_parity_native_accuracy":
                root_summary([r["vanilla_parity_accuracy"] for r in rows]),
            "alternate_branch_retention_delta":root_summary(retention),
            "whole_task_delta":root_summary([r["whole_task_delta"] for r in rows]),
            "positive_root_differences":positive,
            "min_positive_roots":POSITIVE_MIN,
            "min_primary_delta":DELTA_MIN,
            "min_final_native_parity_accuracy":PREFIX_ACC_MIN,
            "min_alternate_retention":ALTERNATE_FLOOR,
            "predeclared_pilot_gate_passed":gate,
            "per_root_in_registration_order":rows,
        })
    decision=(
        "CALIBRATION_AUX_XOR_STAGE_PILOT_PASS_REQUIRES_NEW_HEADROOM_AND_SAE_PROTOCOL"
        if snapshots[-1]["predeclared_pilot_gate_passed"]
        else "STOP_AUX_XOR_STATE_CALIBRATION_PILOT"
    )
    result={
        "schema":SCHEMA,
        "original_source_ledger_sha256":file_sha(ledger_file),
        "root_indices":list(ROOTS),
        "native_arms":list(ARMS),
        "optimizer_steps":list(STEPS),
        "root_statistical_unit":"one original NEC04A CALIBRATION world root",
        "all_six_original_worlds_independently_audited":True,
        "all_36_model_optimizer_checkpoint_shas_replayed":True,
        "all_36_source_and_owned_validation_native_and_aux_logits_replayed":True,
        "all_3_arms_matched_native_initialization_and_minibatches":True,
        "calibration_world_roots":all_root,
        "snapshots":snapshots,
        "decision":decision,
        "selected_native_headroom_budget":None,
        "source_SAE_fitted":False,
        "causal_sham_scored":False,
        "new_original_model_development_WORLD_outcomes":0,
        "new_original_model_confirmation_WORLD_outcomes":0,
        "old_NEC03P_causal_sham_world_results":0,
        "original_calibration_reserved_contexts_scored":0,
        "FSI_01_gate":"REDESIGN_OR_PILOT_ONLY",
    }
    out.mkdir(parents=True,exist_ok=True)
    (out/"nec04f_six_world_auxiliary_XOR_aggregate.json").write_text(
        json.dumps(result,sort_keys=True,indent=2,allow_nan=False)+"\n"
    )
    final=snapshots[-1]
    print("NEC04F_SIX_WORLD_INDEPENDENT_PAIRED_XOR_AUX_RESULT",
          "delta",final["primary_paired_world_delta"]["mean"],
          "roots_positive",final["positive_root_differences"],
          "parity_accuracy",final["aux_prefix_parity_native_accuracy"]["mean"],
          "retention",final["alternate_branch_retention_delta"]["mean"],
          "decision",decision,flush=True)
    return result


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--roots",required=True,type=Path)
    p.add_argument("--pretraining",required=True,type=Path)
    p.add_argument("--out",required=True,type=Path)
    args=p.parse_args()
    aggregate(args.roots,args.pretraining,args.out)


if __name__=="__main__":
    main()
