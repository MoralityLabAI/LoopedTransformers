"""LS-SAE04 strictly calibration-only artifact packaging and independent job loading.

The full fit is defined by its sealed original model/file SHA, 32-Sudoku
roster, canonical array fingerprints and NPZ FILE-BYTE SHA256. The calibration
job is the only place where SAE weights are trained. No heldout test is
generated by this module.
"""
from __future__ import annotations
import hashlib
import json
from pathlib import Path

import numpy as np
import torch
from mechinterp.loopscope02.scripts import trm_sudoku as TS
from mechinterp.sae_causal_transfer.adapter import (
    fingerprint_arrays,to_physical_dictionary
)
from mechinterp.sae_causal_transfer.native_trm_v1 import fit as FIT
from mechinterp.sae_causal_transfer.native_trm_v1 import families as OLD
from mechinterp.sae_causal_transfer.native_jvp_v2 import families as FAM

SCHEMA="LS-SAE04/preheldout-source-frozen-PCA48-top4-SAE96-v1"
PROTOCOL_COMMIT="9e4aa45635b3a2dc6358926aac3ae10e54aaa9d3"
MODEL_SHA=TS.TRM_CHECKPOINTS["gaoxin492"]["sha256"]
ARRAY_KEYS={"schema","mean512","basis","mu","scale","encoder_weight",
            "encoder_bias","decoder_weight","decoder_bias","training_final_loss"}


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def make_pack(fit,roster_sha,checkpoint_sha,npz_path,manifest_path):
    if checkpoint_sha!=MODEL_SHA:
        raise ValueError("native source checkpoint hash changed")
    arrays={
      "schema":np.asarray(SCHEMA),
      "mean512":fit.mean512,"basis":fit.basis,"mu":fit.mu,
      "scale":fit.scale,
      "encoder_weight":fit.sae.encoder.weight.detach().cpu().numpy().copy(),
      "encoder_bias":fit.sae.encoder.bias.detach().cpu().numpy().copy(),
      "decoder_weight":fit.sae.decoder.weight.detach().cpu().numpy().copy(),
      "decoder_bias":fit.sae.decoder.bias.detach().cpu().numpy().copy(),
      "training_final_loss":np.asarray(fit.final_loss,dtype=np.float64),
    }
    physical=fingerprint_arrays(fit.physical_rows,fit.physical_bias,fit.physical_decoder)
    if fit.fingerprint!=fingerprint_arrays(
        fit.mean512,fit.basis,fit.mu,fit.scale,
        arrays["encoder_weight"],arrays["encoder_bias"],arrays["decoder_weight"]):
        raise ValueError("calibration tensor fingerprint calculation differs")
    npz_path=Path(npz_path);npz_path.parent.mkdir(parents=True,exist_ok=True)
    np.savez_compressed(npz_path,**arrays)
    manifest={
      "schema":SCHEMA,
      "protocol_commit":PROTOCOL_COMMIT,
      "preheldout_calibration_only":True,
      "original_checkpoint_file_sha256":checkpoint_sha,
      "calibration_roster_sha256":roster_sha,
      "calibration_seed_base":FAM.BASES["fit_30"],
      "calibration_sample_count":FAM.SIZES["fit_30"],
      "fit_sha256":fit.fingerprint,
      "physical_dictionary_sha256":physical,
      "npz_file_sha256":digest(npz_path),
      "npz_file_bytes":npz_path.stat().st_size,
      "algorithm":"LS-SAE02 PCA48+top4 SAE96/200-update FP32, frozen before LS-SAE04 test",
      "training_final_loss":float(fit.final_loss),
    }
    manifest_path=Path(manifest_path);manifest_path.parent.mkdir(parents=True,exist_ok=True)
    manifest_path.write_text(json.dumps(manifest,indent=2,sort_keys=True)+"\n")
    return manifest


def load_pack(npz_path,manifest_path):
    mpath=Path(manifest_path)
    if not mpath.is_file():
        raise FileNotFoundError("calibration-only manifest missing")
    manifest=json.loads(mpath.read_text())
    if (manifest.get("schema")!=SCHEMA
        or manifest.get("protocol_commit")!=PROTOCOL_COMMIT
        or manifest.get("preheldout_calibration_only") is not True
        or manifest.get("original_checkpoint_file_sha256")!=MODEL_SHA
        or manifest.get("calibration_seed_base")!=FAM.BASES["fit_30"]
        or manifest.get("calibration_sample_count")!=FAM.SIZES["fit_30"]
        or manifest.get("calibration_roster_sha256")!=OLD.fingerprint(FAM.roster("fit_30"))):
        raise ValueError("calibration manifest source/protocol provenance mismatch")
    npz_path=Path(npz_path)
    if not npz_path.is_file() or digest(npz_path)!=manifest["npz_file_sha256"]:
        raise ValueError("calibration artifact original FILE BYTE SHA256 mismatch")
    if npz_path.stat().st_size!=manifest["npz_file_bytes"]:
        raise ValueError("calibration NPZ byte count changed")
    with np.load(npz_path,allow_pickle=False) as loaded:
        if set(loaded.files)!=ARRAY_KEYS or str(loaded["schema"])!=SCHEMA:
            raise ValueError("unexpected saved SAE array schema")
        a={k:loaded[k].copy() for k in loaded.files if k!="schema"}
    shapes={
      "mean512":(512,),"basis":(512,48),"mu":(48,),"scale":(48,),
      "encoder_weight":(96,48),"encoder_bias":(96,),
      "decoder_weight":(48,96),"decoder_bias":(48,)
    }
    if any(a[k].shape!=shape for k,shape in shapes.items()):
        raise ValueError("wrong archived SAE/PCA array dimensions")
    if not all(np.all(np.isfinite(v)) for v in a.values()) or np.any(a["scale"]<=0):
        raise ValueError("nonfinite/invalid archived SAE scale")
    fp=fingerprint_arrays(
        a["mean512"],a["basis"],a["mu"],a["scale"],
        a["encoder_weight"],a["encoder_bias"],a["decoder_weight"])
    E,b,D=to_physical_dictionary(a["encoder_weight"],a["encoder_bias"],
                                  a["decoder_weight"],a["mu"],a["scale"])
    phys=fingerprint_arrays(E,b,D)
    if fp!=manifest["fit_sha256"] or phys!=manifest["physical_dictionary_sha256"]:
        raise ValueError("the sealed calibration PCA/SAE numerical fingerprints differ")
    sae=FIT.SparseTopFour(48,96)
    with torch.no_grad():
        sae.encoder.weight.copy_(torch.tensor(a["encoder_weight"],dtype=torch.float32))
        sae.encoder.bias.copy_(torch.tensor(a["encoder_bias"],dtype=torch.float32))
        sae.decoder.weight.copy_(torch.tensor(a["decoder_weight"],dtype=torch.float32))
        sae.decoder.bias.copy_(torch.tensor(a["decoder_bias"],dtype=torch.float32))
    sae.eval()
    fit=FIT.Fitted(a["mean512"],a["basis"],a["mu"],a["scale"],
                   E,b,D,sae,fp,float(a["training_final_loss"]))
    if not np.isfinite(fit.final_loss):
        raise ValueError("corrupt original source-training objective")
    return fit,manifest,digest(mpath)
